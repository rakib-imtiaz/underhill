/* ==========================================================================
   tools/build-landmask.mjs — generates src/three/landmask.js

   The globe's continents were originally hand-authored lat/lon rings and did
   not read as Earth. This bakes the real Natural Earth 110m coastline into a
   compact run-length-encoded raster so the runtime needs no network, no asset
   file and no polygon maths — just an O(1) lookup per sample.

   Run:  node tools/build-landmask.mjs
   ========================================================================== */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../src/three/landmask.js");

const NE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson";
const LAND_URL = `${NE}/ne_110m_land.geojson`;
const COUNTRIES_URL = `${NE}/ne_110m_admin_0_countries.geojson`;

/* 0.25 degree cells — ~1.7 px of coastline detail at the widest framing */
const W = 1440, H = 720;
const STEP = 360 / W;

async function getJSON(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

/** flatten a GeoJSON feature collection to a flat list of linear rings */
function ringsOf(features) {
  const rings = [];
  for (const f of features) {
    const g = f.geometry;
    if (!g) continue;
    if (g.type === "Polygon") rings.push(...g.coordinates);
    else if (g.type === "MultiPolygon") for (const poly of g.coordinates) rings.push(...poly);
  }
  return rings;
}

/**
 * Scanline-fill rings into a raster.
 * Even-odd across ALL rings pooled: inner rings (lakes) cancel their outer
 * ring, and Natural Earth landmasses never overlap each other, so pooling is
 * safe and much faster than per-polygon point-in-polygon.
 */
function rasterize(rings, mask, bit) {
  /* pre-split rings into edges with their lat span */
  const edges = [];
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j], [x2, y2] = ring[i];
      if (y1 === y2) continue;
      edges.push([x1, y1, x2, y2, Math.min(y1, y2), Math.max(y1, y2)]);
    }
  }
  const xs = [];
  for (let row = 0; row < H; row++) {
    const lat = 90 - (row + 0.5) * STEP;
    xs.length = 0;
    for (let e = 0; e < edges.length; e++) {
      const [x1, y1, x2, y2, lo, hi] = edges[e];
      if (lat < lo || lat >= hi) continue;
      xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
    if (!xs.length) continue;
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      let c0 = Math.ceil((xs[k] + 180) / STEP - 0.5);
      let c1 = Math.floor((xs[k + 1] + 180) / STEP - 0.5);
      if (c1 < 0 || c0 >= W) continue;
      if (c0 < 0) c0 = 0;
      if (c1 >= W) c1 = W - 1;
      const base = row * W;
      for (let c = c0; c <= c1; c++) mask[base + c] |= bit;
    }
  }
}

/* self-delimiting RLE: uppercase letter = cell value, following lowercase
   base36 digits = run length. ~3 chars per run. */
const VAL = "ABCD";
function encode(mask) {
  let out = "", v = mask[0], n = 0;
  const flush = () => { out += VAL[v] + n.toString(36); };
  for (let i = 0; i < mask.length; i++) {
    if (mask[i] === v) { n++; continue; }
    flush(); v = mask[i]; n = 1;
  }
  flush();
  return out;
}

const [land, countries] = await Promise.all([getJSON(LAND_URL), getJSON(COUNTRIES_URL)]);

const mask = new Uint8Array(W * H);
rasterize(ringsOf(land.features), mask, 1);

const ca = countries.features.filter(
  (f) => (f.properties.ADMIN || f.properties.admin) === "Canada"
);
if (!ca.length) throw new Error("Canada not found in admin_0_countries");
rasterize(ringsOf(ca), mask, 2);

let nLand = 0, nCanada = 0;
for (let i = 0; i < mask.length; i++) {
  if (mask[i] & 1) nLand++;
  if (mask[i] & 2) nCanada++;
}

const packed = encode(mask);
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `/* ==========================================================================
   three/landmask.js — GENERATED by tools/build-landmask.mjs. Do not edit.

   Natural Earth 110m coastline + Canada, rasterised to a ${W}x${H} grid
   (${STEP} degree cells) and run-length encoded. Decoded once at module load
   into a Uint8Array: bit 0 = land, bit 1 = Canada.

   Land cells: ${nLand} (${(100 * nLand / mask.length).toFixed(1)}% of grid)
   Canada cells: ${nCanada}
   ========================================================================== */

export const MASK_W = ${W};
export const MASK_H = ${H};
export const MASK_STEP = ${STEP};

const PACKED = "${packed}";

const isMarker = (c) => c >= 65 && c <= 68; // 'A'..'D' — base36 digits are 0-9a-z

function decode() {
  const out = new Uint8Array(MASK_W * MASK_H);
  let i = 0, p = 0;
  while (p < PACKED.length) {
    const v = PACKED.charCodeAt(p++) - 65; // 'A'
    const s = p;
    while (p < PACKED.length && !isMarker(PACKED.charCodeAt(p))) p++;
    const n = parseInt(PACKED.slice(s, p), 36);
    if (v) out.fill(v, i, i + n);
    i += n;
  }
  return out;
}

export const MASK = decode();

/** raster cell value at a geographic position: bit 0 land, bit 1 Canada */
export function maskAt(lat, lon) {
  let col = Math.floor((lon + 180) / MASK_STEP);
  let row = Math.floor((90 - lat) / MASK_STEP);
  if (row < 0) row = 0; else if (row >= MASK_H) row = MASK_H - 1;
  col = ((col % MASK_W) + MASK_W) % MASK_W;
  return MASK[row * MASK_W + col];
}

export const isLand = (lat, lon) => (maskAt(lat, lon) & 1) === 1;
export const isCanada = (lat, lon) => (maskAt(lat, lon) & 2) === 2;

/** true when at least one 4-neighbour cell is ocean — i.e. a coastline cell */
export function isCoast(lat, lon) {
  if (!isLand(lat, lon)) return false;
  const d = MASK_STEP;
  return !isLand(lat + d, lon) || !isLand(lat - d, lon) ||
         !isLand(lat, lon + d) || !isLand(lat, lon - d);
}
`);

console.log(`wrote ${OUT}`);
console.log(`grid ${W}x${H}  land ${nLand} (${(100 * nLand / mask.length).toFixed(1)}%)  canada ${nCanada}`);
console.log(`packed ${(packed.length / 1024).toFixed(1)} KB`);
